package handlers

import (
	"net/http"
	"strconv"
	"strings"

	"github.com/alvindingpeng/switchyard/internal/model"
	"github.com/alvindingpeng/switchyard/internal/op"
	"github.com/alvindingpeng/switchyard/internal/server/middleware"
	"github.com/alvindingpeng/switchyard/internal/server/resp"
	"github.com/alvindingpeng/switchyard/internal/server/router"
	"github.com/gin-gonic/gin"
	"github.com/samber/lo"
)

func init() {
	router.NewGroupRouter("/api/v1/apikey").
		Use(middleware.Auth()).
		Use(middleware.RequireJSON()).
		AddRoute(
			router.NewRoute("/create", http.MethodPost).
				Handle(createAPIKey),
		).
		AddRoute(
			router.NewRoute("/list", http.MethodGet).
				Handle(listAPIKey),
		).
		AddRoute(
			router.NewRoute("/update", http.MethodPost).
				Handle(updateAPIKey),
		).
		AddRoute(
			router.NewRoute("/delete/:id", http.MethodDelete).
				Handle(deleteAPIKey),
		)
	router.NewGroupRouter("/api/v1/apikey").
		Use(middleware.APIKeyAuth()).
		AddRoute(
			router.NewRoute("/stats", http.MethodGet).
				Handle(getStatsAPIKeyById),
		).
		AddRoute(
			router.NewRoute("/login", http.MethodGet).
				Handle(loginAPIKey),
		)
}

func createAPIKey(c *gin.Context) {
	c.Header("Cache-Control", "no-store")
	var req model.APIKey
	if err := c.ShouldBindJSON(&req); err != nil {
		resp.Error(c, http.StatusBadRequest, resp.ErrInvalidJSON)
		return
	}
	// 归属取自登录身份, 不信任请求体。
	if !model.IsValidRoutingPreference(req.RoutingPreference) {
		resp.Error(c, http.StatusBadRequest, "invalid routing_preference")
		return
	}
	if req.RoutingPreference == "" {
		req.RoutingPreference = model.RoutingPreferenceInherit
	}
	userID, _ := middleware.CurrentUser(c)
	req.UserID = userID
	// 客户端不能指定秘密: SHA-256 查找依赖服务端生成的高熵随机凭据。
	if strings.TrimSpace(req.APIKey) != "" {
		resp.Error(c, http.StatusBadRequest, "api key is generated by the server; omit api_key")
		return
	}
	req.ID = 0
	req.KeyHash, req.KeyPrefix, req.KeyLast4 = "", "", ""
	req.APIKey = "" // 明文不从请求里来: 高熵生成收敛在 op.APIKeyCreate。
	if err := op.APIKeyCreate(&req, c.Request.Context()); err != nil {
		resp.Error(c, http.StatusInternalServerError, err.Error())
		return
	}
	// req.APIKey 是 op 生成的高熵明文, 只在这一刻返回一次: 落库只有指纹, 后续任何接口都拿不回明文。
	// 指纹字段带 json:"-", 响应里永远只有掩码片段 key_prefix / key_last4。
	resp.Success(c, req)
}

func listAPIKey(c *gin.Context) {
	userID, role := middleware.CurrentUser(c)
	apiKeys, err := op.APIKeyList(model.Scope{ID: userID, Role: role}, c.Request.Context())
	if err != nil {
		resp.Error(c, http.StatusInternalServerError, err.Error())
		return
	}
	resp.Success(c, apiKeys)
}

func updateAPIKey(c *gin.Context) {
	var req model.APIKeyUpdateRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		resp.Error(c, http.StatusBadRequest, resp.ErrInvalidJSON)
		return
	}
	// Key 一旦签发不可替换: 要换只能新建再删旧, 免得调用方以为换了 Key 而旧 Key 还活着。
	if strings.TrimSpace(req.APIKey) != "" {
		resp.Error(c, http.StatusBadRequest, "api key cannot be replaced; create a new key instead")
		return
	}
	if req.RoutingPreference != nil && *req.RoutingPreference != "" &&
		!model.IsValidRoutingPreference(*req.RoutingPreference) {
		resp.Error(c, http.StatusBadRequest, "invalid routing_preference")
		return
	}
	// 未提交的字段保留原值: 权限与额度不会因为空提交被清零。
	userID, role := middleware.CurrentUser(c)
	updated, err := op.APIKeyUpdate(req.ID, &req, model.Scope{ID: userID, Role: role}, c.Request.Context())
	if err != nil {
		resp.Error(c, http.StatusInternalServerError, err.Error())
		return
	}
	resp.Success(c, updated)
}

func deleteAPIKey(c *gin.Context) {
	id := c.Param("id")
	idNum, err := strconv.Atoi(id)
	if err != nil {
		resp.Error(c, http.StatusBadRequest, resp.ErrInvalidParam)
		return
	}
	userID, role := middleware.CurrentUser(c)
	if err := op.APIKeyDelete(idNum, model.Scope{ID: userID, Role: role}, c.Request.Context()); err != nil {
		resp.Error(c, http.StatusInternalServerError, err.Error())
		return
	}
	resp.Success(c, nil)
}

func getStatsAPIKeyById(c *gin.Context) {
	id := c.GetInt("api_key_id")
	stats := op.StatsAPIKeyGet(id)
	info, err := op.APIKeyGet(id, c.Request.Context())
	if err != nil {
		resp.Error(c, http.StatusInternalServerError, err.Error())
		return
	}
	models := op.GroupListModel(model.Scope{ID: uint(info.UserID), Role: model.RoleUser})
	if len(info.SupportedModels) > 0 {
		models = lo.Filter(models, func(m string, _ int) bool {
			return lo.Contains(info.SupportedModels, m)
		})
	}
	info.SupportedModels = models
	resp.Success(c, map[string]any{
		"stats": stats,
		"info":  info,
	})
}

func loginAPIKey(c *gin.Context) {
	resp.Success(c, nil)
}
